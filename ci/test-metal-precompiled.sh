#!/usr/bin/env bash
set -euo pipefail

build=build-metal-precompiled
cmake -S . -B "$build" -DCMAKE_BUILD_TYPE=Release \
    -DGGML_METAL=ON -DGGML_METAL_EMBED_LIBRARY=ON -DGGML_METAL_EMBED_PRECOMPILED=ON \
    -DGGML_METAL_SHADER_DEBUG=ON -DLLAMA_BUILD_TESTS=ON \
    -DLLAMA_BUILD_EXAMPLES=OFF -DLLAMA_BUILD_SERVER=OFF -DLLAMA_BUILD_TOOLS=OFF
cmake --build "$build" --config Release --target test-backend-ops -j 4

run_case() {
    local name="$1"
    shift
    env "$@" "$build/bin/test-backend-ops" -b MTL0 -o ADD 2>&1 | tee "$build/$name.log"
    grep -Eq '[1-9][0-9]*/[1-9][0-9]* tests passed' "$build/$name.log"
}

run_case precompiled GGML_METAL_TENSOR_DISABLE=1
grep -q 'using embedded precompiled Metal library' "$build/precompiled.log"

run_case source GGML_METAL_TENSOR_DISABLE=1 GGML_METAL_BF16_DISABLE=1
if grep -q 'using embedded precompiled Metal library' "$build/source.log"; then
    echo 'BF16-disabled device unexpectedly loaded precompiled shaders' >&2
    exit 1
fi

autogenerated="$build/ggml/src/ggml-metal/autogenerated"
printf 'invalid metallib' > "$autogenerated/ggml-metal-precompiled.metallib"
touch "$autogenerated/ggml-metal-precompiled.s"
cmake --build "$build" --config Release --target test-backend-ops -j 4
run_case rejected GGML_METAL_TENSOR_DISABLE=1
grep -q 'precompiled Metal library unavailable, compiling source' "$build/rejected.log"
