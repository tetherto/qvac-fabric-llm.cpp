// Prints tests/turbovec-1x-golden.inc: byte-exact outputs of upstream turbovec
// 1.1.2 that test-vector-index.cpp compares the C++ port against.
//
// Inputs come from an integer generator (no libm), so the C++ test rebuilds
// the same f32 values bit for bit on every platform.

use turbovec::rotation::Rotation;
use turbovec::{IdMapIndex, TurboQuantIndex};

fn splitmix64(mut x: u64) -> u64 {
    x = x.wrapping_add(0x9e37_79b9_7f4a_7c15);
    x = (x ^ (x >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
    x = (x ^ (x >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
    x ^ (x >> 31)
}

// Must match turbovec_golden_value() in test-vector-index.cpp.
fn golden_value(seed: u64, row: usize, col: usize, dim: usize) -> f32 {
    let r = splitmix64(seed.wrapping_mul(0x100_0000_01b3) ^ (row * dim + col) as u64);
    let unit = ((r >> 40) as f32) * (1.0 / 16_777_216.0) * 2.0 - 1.0;
    // Per-coordinate scale and offset so a TQ+ fit is not the identity.
    let scale = 0.25 * (1 + col % 7) as f32;
    let offset = 0.125 * (col % 5) as f32;
    unit * scale + offset
}

fn rows(seed: u64, n: usize, dim: usize) -> Vec<f32> {
    let mut out = Vec::with_capacity(n * dim);
    for row in 0..n {
        for col in 0..dim {
            out.push(golden_value(seed, row, col, dim));
        }
    }
    out
}

fn fnv_bytes(hash: &mut u64, bytes: &[u8]) {
    for &b in bytes {
        *hash ^= b as u64;
        *hash = hash.wrapping_mul(0x100_0000_01b3);
    }
}

fn hash_bytes(bytes: &[u8]) -> u64 {
    let mut h = 0xcbf2_9ce4_8422_2325u64;
    fnv_bytes(&mut h, bytes);
    h
}

fn hash_f32(values: &[f32]) -> u64 {
    let mut h = 0xcbf2_9ce4_8422_2325u64;
    for v in values {
        fnv_bytes(&mut h, &v.to_le_bytes());
    }
    h
}

const N_DB: usize = 70;
const N_QUERY: usize = 3;
const K: usize = 5;
const N_CALIB: usize = 1024;
const SEED_DB: u64 = 1;
const SEED_QUERY: u64 = 2;
const SEED_CALIB: u64 = 3;
const SEED_ROTATION: u64 = 4;
const SEED_SHORT_NOISE: u64 = 5;

fn ids(n: usize) -> Vec<u64> {
    (0..n as u64).map(|i| 1000 + 7 * i).collect()
}

fn main() {
    // Upstream picks its 4-bit kernel by host: the int8 permute-dot kernel on
    // aarch64 dotprod / x86 AVX-512 VNNI, the nibble-LUT scan elsewhere, and
    // the two round scores differently. `--vector-major` prints the 4-bit
    // searches under the permute-dot kernel (run it on such a host); the
    // default output pins the LUT scan so it does not depend on the machine.
    if std::env::args().any(|a| a == "--vm8-2bit-section") {
        // Child of `--vector-major`, run with TURBOVEC_2BIT_VM8=1.
        print_vm8_2bit_section();
        return;
    }
    if std::env::args().any(|a| a == "--vector-major") {
        print_vector_major();
        print_batch_section();
        return;
    }
    if std::env::args().any(|a| a == "--staged") {
        print_staged();
        return;
    }
    std::env::set_var("TURBOVEC_NO_VECTOR_MAJOR", "1");
    println!("// Generated by tests/turbovec-golden-gen-1x (turbovec =1.1.2). Do not edit.");
    println!("// Scores are upstream's nibble-LUT kernel (TURBOVEC_NO_VECTOR_MAJOR=1).");
    println!("// Regenerate: cargo run --release --manifest-path tests/turbovec-golden-gen-1x/Cargo.toml > tests/turbovec-1x-golden.inc");
    println!("#pragma once");
    println!("#include <cstddef>");
    println!("#include <cstdint>");
    println!();
    println!("static constexpr int kTv1xNDb = {N_DB};");
    println!("static constexpr int kTv1xNQuery = {N_QUERY};");
    println!("static constexpr int kTv1xK = {K};");
    println!("static constexpr int kTv1xNCalib = {N_CALIB};");
    println!("static constexpr uint64_t kTv1xSeedDb = {SEED_DB};");
    println!("static constexpr uint64_t kTv1xSeedQuery = {SEED_QUERY};");
    println!("static constexpr uint64_t kTv1xSeedCalib = {SEED_CALIB};");
    println!("static constexpr uint64_t kTv1xSeedRotation = {SEED_ROTATION};");
    println!();

    // Rotation: hash of Rotation::apply over one generated row per dim.
    println!("struct Tv1xRotationCase {{ int dim; uint64_t hash; }};");
    println!("static constexpr Tv1xRotationCase kTv1xRotationCases[] = {{");
    for dim in [8usize, 64, 128, 200, 384, 1000, 1536, 3072, 16384] {
        let mut row = rows(SEED_ROTATION, 1, dim);
        Rotation::new(dim).apply(&mut row);
        println!("    {{ {dim}, UINT64_C(0x{:016x}) }},", hash_f32(&row));
    }
    println!("}};");
    println!();

    // Codebooks: exact f32 bits.
    println!("struct Tv1xCodebookCase {{ int bits; int dim; uint64_t boundaries_hash; uint64_t centroids_hash; }};");
    println!("static constexpr Tv1xCodebookCase kTv1xCodebookCases[] = {{");
    for bits in 2..=4usize {
        for dim in [8usize, 128, 200, 768, 1000, 1536, 3072] {
            let (b, c) = turbovec::expected_codebook(bits, dim);
            println!(
                "    {{ {bits}, {dim}, UINT64_C(0x{:016x}), UINT64_C(0x{:016x}) }},",
                hash_f32(&b),
                hash_f32(&c)
            );
        }
    }
    println!("}};");
    println!();

    // Encode / calibrate / re-encode / search per (bits, dim).
    println!("struct Tv1xIndexCase {{");
    println!("    int bits; int dim;");
    println!("    uint64_t codes_hash; uint64_t scales_hash;");
    println!("    uint64_t calib_shift_hash; uint64_t calib_scale_hash;");
    println!("    uint64_t calibrated_codes_hash; uint64_t calibrated_scales_hash;");
    println!("    uint64_t reencoded_codes_hash; uint64_t reencoded_scales_hash;");
    println!("    uint64_t search_ids[{N_QUERY} * {K}]; float search_scores[{N_QUERY} * {K}];");
    println!("    uint64_t calibrated_search_ids[{N_QUERY} * {K}]; float calibrated_search_scores[{N_QUERY} * {K}];");
    println!("    uint64_t snapshot_hash; size_t snapshot_len;");
    println!("    uint64_t calibrated_snapshot_hash; size_t calibrated_snapshot_len;");
    println!("}};");
    println!("static const Tv1xIndexCase kTv1xIndexCases[] = {{");
    for bits in 2..=4usize {
        for dim in [128usize, 200, 1536] {
            let mut db = rows(SEED_DB, N_DB, dim);
            // Row 0 is the zero vector: no direction, scale 0.
            for v in &mut db[..dim] {
                *v = 0.0;
            }
            let queries = rows(SEED_QUERY, N_QUERY, dim);
            let calib = rows(SEED_CALIB, N_CALIB, dim);
            let id_list = ids(N_DB);

            let mut plain = TurboQuantIndex::new(dim, bits).unwrap();
            plain.add(&db);
            let codes_hash = hash_bytes(plain.packed_codes());
            let scales_hash = hash_f32(plain.scales());

            let mut calibrated = TurboQuantIndex::new(dim, bits).unwrap();
            calibrated.calibrate(&calib).unwrap();
            let shift_hash = hash_f32(calibrated.tqplus_shift());
            let scale_hash = hash_f32(calibrated.tqplus_scale());
            calibrated.add(&db);
            let cal_codes_hash = hash_bytes(calibrated.packed_codes());
            let cal_scales_hash = hash_f32(calibrated.scales());

            plain.calibrate(&calib).unwrap();
            let re_codes_hash = hash_bytes(plain.packed_codes());
            let re_scales_hash = hash_f32(plain.scales());

            let mut id_index = IdMapIndex::new(dim, bits).unwrap();
            id_index.add_with_ids(&db, &id_list).unwrap();
            let (scores, out_ids) = id_index.search(&queries, K);
            let snapshot = id_index.to_bytes();

            let mut id_calibrated = IdMapIndex::new(dim, bits).unwrap();
            id_calibrated.calibrate(&calib).unwrap();
            id_calibrated.add_with_ids(&db, &id_list).unwrap();
            let (cal_scores, cal_ids) = id_calibrated.search(&queries, K);
            let cal_snapshot = id_calibrated.to_bytes();

            let fmt_ids = |v: &[u64]| v.iter().map(|x| format!("{x}u")).collect::<Vec<_>>().join(", ");
            let fmt_f32 = |v: &[f32]| {
                v.iter()
                    .map(|x| format!("{:.9e}f", x))
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            println!("    {{ {bits}, {dim},");
            println!("      UINT64_C(0x{codes_hash:016x}), UINT64_C(0x{scales_hash:016x}),");
            println!("      UINT64_C(0x{shift_hash:016x}), UINT64_C(0x{scale_hash:016x}),");
            println!("      UINT64_C(0x{cal_codes_hash:016x}), UINT64_C(0x{cal_scales_hash:016x}),");
            println!("      UINT64_C(0x{re_codes_hash:016x}), UINT64_C(0x{re_scales_hash:016x}),");
            println!("      {{ {} }},", fmt_ids(&out_ids));
            println!("      {{ {} }},", fmt_f32(&scores));
            println!("      {{ {} }},", fmt_ids(&cal_ids));
            println!("      {{ {} }},", fmt_f32(&cal_scores));
            println!(
                "      UINT64_C(0x{:016x}), {}, UINT64_C(0x{:016x}), {} }},",
                hash_bytes(&snapshot),
                snapshot.len(),
                hash_bytes(&cal_snapshot),
                cal_snapshot.len()
            );
        }
    }
    println!("}};");
    println!();

    // Incremental sync: the file after each step, hashed with the per-file
    // random nonce and the superblock CRC (which covers it) zeroed.
    println!("struct Tv1xSyncCase {{ int bits; int dim; uint64_t step_hashes[6]; size_t step_lens[6]; uint64_t final_ids[{N_QUERY} * {K}]; }};");
    println!("static const Tv1xSyncCase kTv1xSyncCases[] = {{");
    let dir = std::env::temp_dir().join(format!("tv1x-sync-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    for bits in 2..=4usize {
        let dim = 128usize;
        let path = dir.join(format!("sync-q{bits}.tvim"));
        let _ = std::fs::remove_file(&path);
        let all = rows(SEED_DB, 160, dim);
        let all_ids = ids(160);
        let row_range = |a: usize, b: usize| all[a * dim..b * dim].to_vec();
        let n_levels = 1usize << bits;
        let masked = |path: &std::path::Path, n_calib: usize| -> (u64, usize) {
            let mut bytes = std::fs::read(path).unwrap();
            let sb_len = 24 + (n_levels - 1) * 4 + n_levels * 4 + 4 + n_calib * 8 + 4;
            for b in &mut bytes[12..20] {
                *b = 0;
            }
            for b in &mut bytes[sb_len - 4..sb_len] {
                *b = 0;
            }
            (hash_bytes(&bytes), bytes.len())
        };
        let mut idx = IdMapIndex::new(dim, bits).unwrap();
        let mut hashes = Vec::new();
        // Step 0: first sync, a full write.
        idx.add_with_ids(&row_range(0, 70), &all_ids[0..70]).unwrap();
        idx.sync(&path).unwrap();
        hashes.push(masked(&path, 0));
        // Step 1: appends complete the tail block and add whole blocks.
        idx.add_with_ids(&row_range(70, 120), &all_ids[70..120]).unwrap();
        idx.sync(&path).unwrap();
        hashes.push(masked(&path, 0));
        // Step 2: removals inside committed blocks become redo ops.
        for i in [5usize, 40, 100, 119] {
            assert!(idx.remove(all_ids[i]));
        }
        idx.sync(&path).unwrap();
        hashes.push(masked(&path, 0));
        // Step 3: more removals and appends; earlier ops materialize.
        for i in [6usize, 64, 33] {
            assert!(idx.remove(all_ids[i]));
        }
        idx.add_with_ids(&row_range(120, 130), &all_ids[120..130]).unwrap();
        idx.sync(&path).unwrap();
        hashes.push(masked(&path, 0));
        // Step 4: a sync with nothing changed commits a new generation.
        idx.sync(&path).unwrap();
        hashes.push(masked(&path, 0));
        // Step 5: a calibrate re-encodes every row, so the next sync
        // rewrites the file.
        idx.calibrate(&rows(SEED_CALIB, N_CALIB, dim)).unwrap();
        idx.sync(&path).unwrap();
        hashes.push(masked(&path, dim));
        let loaded = IdMapIndex::load(&path).unwrap();
        let (_, final_ids) = loaded.search(&rows(SEED_QUERY, N_QUERY, dim), K);
        print!("    {{ {bits}, {dim}, {{ ");
        print!("{}", hashes.iter().map(|(h, _)| format!("UINT64_C(0x{h:016x})")).collect::<Vec<_>>().join(", "));
        print!(" }}, {{ ");
        print!("{}", hashes.iter().map(|(_, l)| format!("{l}")).collect::<Vec<_>>().join(", "));
        print!(" }}, {{ ");
        print!("{}", final_ids.iter().map(|x| format!("{x}u")).collect::<Vec<_>>().join(", "));
        println!(" }} }},");
    }
    let _ = std::fs::remove_dir_all(&dir);
    println!("}};");
    println!();

    // A snapshot after removals: rows sit in swap-remove order.
    println!("struct Tv1xHistoryCase {{ int bits; uint64_t snapshot_hash; size_t snapshot_len; }};");
    println!("static const Tv1xHistoryCase kTv1xHistoryCases[] = {{");
    for bits in 2..=4usize {
        let dim = 128usize;
        let all = rows(SEED_DB, 80, dim);
        let all_ids = ids(80);
        let mut idx = IdMapIndex::new(dim, bits).unwrap();
        idx.add_with_ids(&all[..70 * dim], &all_ids[..70]).unwrap();
        for i in [5usize, 40, 69, 0] {
            assert!(idx.remove(all_ids[i]));
        }
        idx.add_with_ids(&all[70 * dim..75 * dim], &all_ids[70..75]).unwrap();
        assert!(idx.remove(all_ids[71]));
        let bytes = idx.to_bytes();
        println!("    {{ {bits}, UINT64_C(0x{:016x}), {} }},", hash_bytes(&bytes), bytes.len());
    }
    println!("}};");
    println!();

    // One small snapshot spelled out for byte-level diagnostics. The image
    // is the superblock, two fixed-size header slots (slot 0 used prefix,
    // then zero padding; slot 1 all zero) and the block units, so only the
    // non-padding pieces are printed and the test rebuilds the rest.
    let dim = 128usize;
    let bits = 4usize;
    let db = rows(SEED_DB, N_DB, dim);
    let mut id_index = IdMapIndex::new(dim, bits).unwrap();
    id_index.add_with_ids(&db, &ids(N_DB)).unwrap();
    let image = id_index.to_bytes();
    let n_levels = 1usize << bits;
    let row_bytes = dim / (8 / bits);
    let sb_len = 24 + (n_levels - 1) * 4 + n_levels * 4 + 4 + 4;
    let max_ops = 1024usize;
    let op_size = 1 + row_bytes + 4 + 8;
    let hdr_len = 16 + 31 * (row_bytes + 4 + 8) + 4 + max_ops * (5 + op_size) + 4 + max_ops * 4 + 12 + 4;
    let n_tail = N_DB % 32;
    let hdr_used = 16 + n_tail * (row_bytes + 4 + 8) + 4 + 4 + 8 + 4 + 4;
    let units_at = sb_len + 2 * hdr_len;
    assert!(image[sb_len + hdr_used..units_at].iter().all(|&b| b == 0));
    let print_bytes = |name: &str, bytes: &[u8]| {
        println!("static const uint8_t {name}[] = {{");
        for chunk in bytes.chunks(24) {
            let line = chunk.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(",");
            println!("    {line},");
        }
        println!("}};");
    };
    println!("static constexpr int kTv1xImageDim = {dim};");
    println!("static constexpr int kTv1xImageBits = {bits};");
    println!("static constexpr size_t kTv1xImageLen = {};", image.len());
    println!("static constexpr size_t kTv1xImageHeaderLen = {hdr_len};");
    print_bytes("kTv1xImageSuperblock", &image[..sb_len]);
    print_bytes("kTv1xImageHeader0", &image[sb_len..sb_len + hdr_used]);
    print_bytes("kTv1xImageUnits", &image[units_at..]);
}

// The incremental-sync scenario's final 4-bit search, under whichever kernel
// this process runs (see print_vector_major).
fn sync_scenario_final_ids(bits: usize) -> Vec<u64> {
    let dim = 128usize;
    let dir = std::env::temp_dir().join(format!("tv1x-sync-vm-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join("sync.tvim");
    let all = rows(SEED_DB, 160, dim);
    let all_ids = ids(160);
    let row_range = |a: usize, b: usize| all[a * dim..b * dim].to_vec();
    let mut idx = IdMapIndex::new(dim, bits).unwrap();
    idx.add_with_ids(&row_range(0, 70), &all_ids[0..70]).unwrap();
    idx.sync(&path).unwrap();
    idx.add_with_ids(&row_range(70, 120), &all_ids[70..120]).unwrap();
    idx.sync(&path).unwrap();
    for i in [5usize, 40, 100, 119] {
        assert!(idx.remove(all_ids[i]));
    }
    idx.sync(&path).unwrap();
    for i in [6usize, 64, 33] {
        assert!(idx.remove(all_ids[i]));
    }
    idx.add_with_ids(&row_range(120, 130), &all_ids[120..130]).unwrap();
    idx.sync(&path).unwrap();
    idx.sync(&path).unwrap();
    idx.calibrate(&rows(SEED_CALIB, N_CALIB, dim)).unwrap();
    idx.sync(&path).unwrap();
    let loaded = IdMapIndex::load(&path).unwrap();
    let (_, final_ids) = loaded.search(&rows(SEED_QUERY, N_QUERY, dim), K);
    let _ = std::fs::remove_dir_all(&dir);
    final_ids
}

fn print_vector_major() {
    println!("// Generated by tests/turbovec-golden-gen-1x --vector-major (turbovec =1.1.2). Do not edit.");
    println!("// 4-bit searches under upstream's permute-dot kernel; generate on an aarch64");
    println!("// host with dot product or an x86 host with AVX-512 VBMI and VNNI.");
    println!("// Regenerate: cargo run --release --manifest-path tests/turbovec-golden-gen-1x/Cargo.toml -- --vector-major > tests/turbovec-1x-golden-vm.inc");
    println!("#pragma once");
    println!("struct Tv1xVmCase {{ int dim; uint64_t search_ids[{N_QUERY} * {K}]; float search_scores[{N_QUERY} * {K}]; uint64_t calibrated_search_ids[{N_QUERY} * {K}]; float calibrated_search_scores[{N_QUERY} * {K}]; }};");
    println!("static const Tv1xVmCase kTv1xVmCases[] = {{");
    for dim in [128usize, 200, 1536] {
        let mut db = rows(SEED_DB, N_DB, dim);
        for v in &mut db[..dim] {
            *v = 0.0;
        }
        let queries = rows(SEED_QUERY, N_QUERY, dim);
        let calib = rows(SEED_CALIB, N_CALIB, dim);
        let id_list = ids(N_DB);
        let mut plain = IdMapIndex::new(dim, 4).unwrap();
        plain.add_with_ids(&db, &id_list).unwrap();
        let (scores, out_ids) = plain.search(&queries, K);
        let mut calibrated = IdMapIndex::new(dim, 4).unwrap();
        calibrated.calibrate(&calib).unwrap();
        calibrated.add_with_ids(&db, &id_list).unwrap();
        let (cal_scores, cal_ids) = calibrated.search(&queries, K);
        let fmt_ids = |v: &[u64]| v.iter().map(|x| format!("{x}u")).collect::<Vec<_>>().join(", ");
        let fmt_f32 = |v: &[f32]| v.iter().map(|x| format!("{:.9e}f", x)).collect::<Vec<_>>().join(", ");
        println!("    {{ {dim},");
        println!("      {{ {} }},", fmt_ids(&out_ids));
        println!("      {{ {} }},", fmt_f32(&scores));
        println!("      {{ {} }},", fmt_ids(&cal_ids));
        println!("      {{ {} }} }},", fmt_f32(&cal_scores));
    }
    println!("}};");
    let ids4 = sync_scenario_final_ids(4);
    println!("static const uint64_t kTv1xVmSyncFinalIds4[{N_QUERY} * {K}] = {{ {} }};",
        ids4.iter().map(|x| format!("{x}u")).collect::<Vec<_>>().join(", "));
}

// Staged (planes) searches. Upstream runs them from 32,768 vectors on
// aarch64 (4 bits with dot product) and x86 with AVX-512 VBMI and VNNI, and
// its results depend on the pool size: run with RAYON_NUM_THREADS=1 on an
// aarch64 host with dot product for the single-threaded path the port follows.
fn print_staged() {
    const N: usize = 40_000;
    const DIM: usize = 128;
    const KS: usize = 10;
    println!("// Generated by tests/turbovec-golden-gen-1x --staged (turbovec =1.1.2). Do not edit.");
    println!("// Upstream's staged (planes) search, single-threaded, on aarch64 with dot product.");
    println!("// Regenerate: RAYON_NUM_THREADS=1 cargo run --release --manifest-path tests/turbovec-golden-gen-1x/Cargo.toml -- --staged > tests/turbovec-1x-golden-staged.inc");
    println!("#pragma once");
    println!("static constexpr int kTv1xStagedN = {N};");
    println!("static constexpr int kTv1xStagedDim = {DIM};");
    println!("static constexpr int kTv1xStagedK = {KS};");
    println!("struct Tv1xStagedSnapshot {{ int bits; int calibrated; uint64_t hash; size_t len; }};");
    println!("struct Tv1xStagedCase {{ int bits; int calibrated; int nq; int filtered; uint64_t ids[3 * {KS}]; float scores[3 * {KS}]; }};");
    println!("static const Tv1xStagedCase kTv1xStagedCases[] = {{");
    let db = rows(SEED_DB, N, DIM);
    let id_list = ids(N);
    let queries = rows(SEED_QUERY, 3, DIM);
    let calib = rows(SEED_CALIB, N_CALIB, DIM);
    let allow: Vec<u64> = id_list.iter().copied().step_by(3).collect();
    let mut snapshots = Vec::new();
    for bits in [2usize, 4] {
        for calibrated in [0, 1] {
            let mut idx = IdMapIndex::new(DIM, bits).unwrap();
            if calibrated == 1 {
                idx.calibrate(&calib).unwrap();
            }
            idx.add_with_ids(&db, &id_list).unwrap();
            // A search builds upstream's planes cache, which a snapshot then
            // stores in the planes unit layout.
            let _ = idx.search(&queries[..DIM], 1);
            let bytes = idx.to_bytes();
            snapshots.push((bits, calibrated, hash_bytes(&bytes), bytes.len()));
            for nq in [1usize, 3] {
                for filtered in [0, 1] {
                    let mut out_ids = Vec::new();
                    let mut out_scores = Vec::new();
                    if nq == 1 {
                        // One call per query: each is a single-query search.
                        for q in 0..3 {
                            let query = &queries[q * DIM..(q + 1) * DIM];
                            let (s, i) = if filtered == 1 {
                                idx.search_with_allowlist(query, KS, Some(&allow)).unwrap()
                            } else {
                                idx.search(query, KS)
                            };
                            out_scores.extend(s);
                            out_ids.extend(i);
                        }
                    } else {
                        let (s, i) = if filtered == 1 {
                            idx.search_with_allowlist(&queries, KS, Some(&allow)).unwrap()
                        } else {
                            idx.search(&queries, KS)
                        };
                        out_scores = s;
                        out_ids = i;
                    }
                    let fmt_ids = out_ids.iter().map(|x| format!("{x}u")).collect::<Vec<_>>().join(", ");
                    let fmt_f32 = out_scores.iter().map(|x| format!("{:.9e}f", x)).collect::<Vec<_>>().join(", ");
                    println!("    {{ {bits}, {calibrated}, {nq}, {filtered},");
                    println!("      {{ {fmt_ids} }},");
                    println!("      {{ {fmt_f32} }} }},");
                }
            }
        }
    }
    println!("}};");
    println!("static const Tv1xStagedSnapshot kTv1xStagedSnapshots[] = {{");
    for (bits, calibrated, hash, len) in snapshots {
        println!("    {{ {bits}, {calibrated}, UINT64_C(0x{hash:016x}), {len} }},");
    }
    println!("}};");
    print_staged_short();
}

// A batch of three in which only query 0's sampled seed runs short: near
// copies of it fill exactly the 48 blocks upstream samples, so the seed
// lands above all but a handful of rows. Upstream then rescans that one
// query with the single-query sign tables.
fn print_staged_short() {
    const N: usize = 40_000;
    const DIM: usize = 128;
    const KS: usize = 100;
    println!("static constexpr int kTv1xStagedShortK = {KS};");
    println!("static constexpr uint64_t kTv1xStagedShortNoiseSeed = {SEED_SHORT_NOISE};");
    println!("struct Tv1xStagedShortCase {{ int bits; int calibrated; uint64_t ids[3 * {KS}]; float scores[3 * {KS}]; }};");
    println!("static const Tv1xStagedShortCase kTv1xStagedShortCases[] = {{");
    let mut db = rows(SEED_DB, N, DIM);
    let id_list = ids(N);
    let queries = rows(SEED_QUERY, 3, DIM);
    let calib = rows(SEED_CALIB, N_CALIB, DIM);
    let noise = rows(SEED_SHORT_NOISE, 48 * 32, DIM);
    let stride = (N / 32) / 48;
    for i in 0..48 {
        let block = i * stride + stride / 2;
        for lane in 0..32 {
            let row = block * 32 + lane;
            for c in 0..DIM {
                db[row * DIM + c] = queries[c] + 0.05 * noise[(i * 32 + lane) * DIM + c];
            }
        }
    }
    for bits in [2usize, 4] {
        for calibrated in [0, 1] {
            let mut idx = IdMapIndex::new(DIM, bits).unwrap();
            if calibrated == 1 {
                idx.calibrate(&calib).unwrap();
            }
            idx.add_with_ids(&db, &id_list).unwrap();
            let (s, i) = idx.search(&queries, KS);
            let fmt_ids = i.iter().map(|x| format!("{x}u")).collect::<Vec<_>>().join(", ");
            let fmt_f32 = s.iter().map(|x| format!("{:.9e}f", x)).collect::<Vec<_>>().join(", ");
            println!("    {{ {bits}, {calibrated},");
            println!("      {{ {fmt_ids} }},");
            println!("      {{ {fmt_f32} }} }},");
        }
    }
    println!("}};");
}

// Batched searches: upstream fuses 12, 8 or 4 queries (`pd_scan`) and runs
// a remainder query by query, so 20 queries take the 12 and 8 widths and 6
// queries the 4 and the single-query path; 16 is 12 + 4 and 11 is 8 + 3
// single queries. Appended to the vector-major fixture; the rows above stay
// byte-identical.
const BATCH_NQS: [usize; 4] = [20, 16, 11, 6];
const BATCH_MAX_NQ: usize = 20;

fn batch_case_rows(bits: usize) -> Vec<String> {
    let mut out = Vec::new();
    for dim in [128usize, 200, 1536] {
        let mut db = rows(SEED_DB, N_DB, dim);
        for v in &mut db[..dim] {
            *v = 0.0;
        }
        let calib = rows(SEED_CALIB, N_CALIB, dim);
        let id_list = ids(N_DB);
        let allow: Vec<u64> = id_list.iter().copied().step_by(3).collect();
        let mut plain = IdMapIndex::new(dim, bits).unwrap();
        plain.add_with_ids(&db, &id_list).unwrap();
        let mut calibrated = IdMapIndex::new(dim, bits).unwrap();
        calibrated.calibrate(&calib).unwrap();
        calibrated.add_with_ids(&db, &id_list).unwrap();
        for nq in BATCH_NQS {
            let queries = rows(SEED_QUERY, nq, dim);
            for (cal, filt) in [(0, 0), (1, 0), (0, 1)] {
                let idx = if cal == 1 { &calibrated } else { &plain };
                let (scores, out_ids) = if filt == 1 {
                    idx.search_with_allowlist(&queries, K, Some(&allow)).unwrap()
                } else {
                    idx.search(&queries, K)
                };
                assert_eq!(out_ids.len(), nq * K);
                let fmt_ids = out_ids.iter().map(|x| format!("{x}u")).collect::<Vec<_>>().join(", ");
                let fmt_f32 = scores.iter().map(|x| format!("{:.9e}f", x)).collect::<Vec<_>>().join(", ");
                out.push(format!("    {{ {bits}, {dim}, {cal}, {filt}, {nq},\n      {{ {fmt_ids} }},\n      {{ {fmt_f32} }} }},"));
            }
        }
    }
    out
}

fn print_batch_section() {
    println!();
    println!("// Batched searches (20, 16, 11 and 6 queries; plain, calibrated, and every third id");
    println!("// allowed). 4-bit under the permute-dot kernel, 2-bit under the nibble LUT.");
    println!("struct Tv1xBatchCase {{ int bits; int dim; int calibrated; int filtered; int n_q; uint64_t ids[{BATCH_MAX_NQ} * {K}]; float scores[{BATCH_MAX_NQ} * {K}]; }};");
    println!("static const Tv1xBatchCase kTv1xBatchCases[] = {{");
    for bits in [4usize, 2] {
        for row in batch_case_rows(bits) {
            println!("{row}");
        }
    }
    println!("}};");
    // The same 2-bit searches under TURBOVEC_2BIT_VM8=1, which upstream
    // reads once per process: a child process prints them.
    let exe = std::env::current_exe().unwrap();
    let child = std::process::Command::new(exe)
        .arg("--vm8-2bit-section")
        .env("TURBOVEC_2BIT_VM8", "1")
        .output()
        .unwrap();
    assert!(child.status.success(), "{}", String::from_utf8_lossy(&child.stderr));
    print!("{}", String::from_utf8(child.stdout).unwrap());
}

fn print_vm8_2bit_section() {
    // The opt-in only changes anything on aarch64 with i8mm; elsewhere these
    // rows would silently repeat the LUT ones.
    #[cfg(target_arch = "aarch64")]
    assert!(std::arch::is_aarch64_feature_detected!("i8mm"), "the 2-bit vm8 rows need aarch64 with i8mm");
    #[cfg(not(target_arch = "aarch64"))]
    panic!("the 2-bit vm8 rows need aarch64 with i8mm");
    assert_eq!(std::env::var("TURBOVEC_2BIT_VM8").as_deref(), Ok("1"));
    println!();
    println!("// The 2-bit batched searches under TURBOVEC_2BIT_VM8=1 (aarch64 with i8mm):");
    println!("// dims whose byte-group count is a multiple of 8 take the vm8 layout, where");
    println!("// batches of 12, 8 and 4 score with SMMLA and other queries with the LUT.");
    println!("static const Tv1xBatchCase kTv1xVm8TwoBitCases[] = {{");
    for row in batch_case_rows(2) {
        println!("{row}");
    }
    println!("}};");
}
